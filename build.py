def pack(files, out_name):
    data = {}
    for k, p in files.items():
        data[k] = base64.b64encode(gzip.compress(open(p, 'rb').read(), 9)).decode()
    with open(os.path.join(OUT, out_name), 'w') as f:
        f.write('// gzip+base64 FBX data, generated by build.py\nexport default ' + json.dumps(data) + ';\n')
    return os.path.getsize(os.path.join(OUT, out_name))


